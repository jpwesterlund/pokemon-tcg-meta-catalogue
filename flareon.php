        <section>
            <h3>Key Cards</h3>

            <ul>
                <li>
                    <strong>ACE Spec:</strong> The only real choice for an ACE Spec is
                    Sparkling Crystal. Since the deck’s main attackers are Tera Pokemon and many of
                    their attacks require three different Energy, Sparkling Crystal allows the deck to power up an attacker in a
                    single turn when paired with Crispin.
                </li>

                <li>
                    <strong>Flareon ex:</strong> Flareon is the deck’s primary attacker and Energy accelerator.
                    Burning Charge helps set up future attackers, and its second attack Carnelia hits for
                    clean 280 damage.
                </li>

                <li>
                    <strong>Sylveon ex:</strong> Sylveon is an interesting secondary attacker. Its Angelite attack lets you
                    shuffle two of the opponent’s Benched Pokemon and all attached cards back into their deck. Against
                    Stage 2 decks, this can force the opponent to find the Basic Pokemon again, evolve back up, and
                    reattach the necessary Energy. It's worth noting that Angelite cannot be used twice in a row.
                </li>

                <li>
                    <strong>Noctowl:</strong> Because the deck is built around Tera Pokemon, Noctowl is required to consistently
                    find combo pieces. Searching for any two Trainer cards helps the deck access Crispin, Sparkling
                    Crystal, Area Zero Underdepths, Boss’s Orders, etc.
                </li>

                <li>
                    <strong>Terapagos ex:</strong> Terapagos gives the deck another powerful attacker
                    when paired with Area Zero Underdepths, often in the late game. Oftentimes the deck wants to take 
                    two KOs with Flareon and then clean up with Terapagos.

                </li>
            </ul>
        </section>

