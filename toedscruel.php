        <!-- Key Cards -->
        <section>
            <h3>Key Cards</h3>

            <ul>
                <li>
                    <strong>ACE Spec:</strong> Because Toedscruel wants to be the aggressor,
                    Prime Catcher is the most logical ACE Spec. Ray Chen notes in his guide that
                    Precious Trolley and Secret Box are options worth considering, but
                    Prime Catcher is favored.
                </li>

                <li>
                    <strong>Toedscruel ex:</strong> Toedscruel is both the deck's main attacker and its defining ability. Protective Mycelium 
                    protects Pokemon with Grass Energy attached from attack effects, while its
                    attack scales with the number of Pokemon with Grass Energy attached in play.
                </li>

                <li>
                    <strong>Teal Mask Ogerpon ex:</strong> Teal Mask Ogerpon is the deck’s energy acceleration.
                    Teal Dance attaches Grass Energy to itself and draws a card. It also becomes a target for 
                    Energy Switch to protect benched Pokemon from effects of attacks and increase Toedscruel's damage output.
                </li>

                <li>
                    <strong>Energy Switch:</strong> Energy Switch turns Ogerpon’s self-acceleration into board-wide
                    Energy placement. This is what lets Toedscruel load Grass Energy across the bench and reach massive
                    damage numbers.
                </li>

                <li>
                    <strong>Bug Catching Set:</strong> Bug Catching Set is one of the deck’s most important cards. It
                    lets you look at the top seven cards of your deck and put up to two Grass Pokemon and/or Grass
                    Energy into your hand, helping you find both Ogerpon and the Energy needed to start the engine.
                </li>

                <li>
                    <strong>Area Zero Underdepths:</strong> Since Teal Mask Ogerpon ex is a Tera Pokemon, Area Zero
                    Underdepths can expand your bench to eight. A wider bench gives Toedscruel more Pokemon to attach
                    Grass Energy to, directly raising its damage ceiling.
                </li>
            </ul>
        </section>

