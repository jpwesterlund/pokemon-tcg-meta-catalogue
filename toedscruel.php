            <h3>Archetype Overview</h3>

            <p>
                Considered a rogue deck before <strong>Ray Chen</strong> piloted it to a 5th place finish at NAIC,
                <strong>Toedscruel ex</strong> made a name for itself as an anti-meta deck. Toedscruel is uniquely
                positioned because it hits for weakness against both the newly emerging
                Marnie’s Grimmsnarl ex archetype and the old favorite Charizard ex.
            </p>

            <p>
                Its Protective Mycelium ability protects any Pokemon with a Grass Energy attached from the
                effects of the opponent’s attacks. The biggest victim of this is Dragapult ex’s 
                Phantom Dive spread damage. Toedscruel itself is also a very aggressive attacker. 
                Its attack damage increases for each of your Pokemon that has a Grass Energy attached.
            </p>

            <p>
                The general strategy is to use Teal Mask Ogerpon ex's Teal Dance Ability to
                accelerate Grass Energy to itself while also drawing a card. Then use Energy Switch to
                spread that energy to your benched Pokemon. Since Teal Mask Ogerpon ex is a Tera Pokemon,
                Area Zero Underdepths can expand your bench to eight.
            </p>

            <p>
                If each benched Pokemon has a Grass Energy attached and the bench is fully expanded,
                Toedscruel ex can hit for 400 damage, which is more than enough to one-hit KO anything in
                the game.
            </p>
        </section>

