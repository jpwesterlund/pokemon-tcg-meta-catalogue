        <section>
            <h3>Key Cards</h3>

            <ul>
                <li>
                    <strong>ACE Spec:</strong> The most popular ACE Spec choice for Charizard is
                    Maximum Belt, which heightens Charizard's already high damage ceiling.
                    That said, Charizard is strong enough to run other ACE Spec options like
                    Prime Catcher or Unfair Stamp and still perform well.
                </li>

                <li>
                    <strong>Charizard ex:</strong> Charizard is the deck’s main attacker.
                    Infernal Reign accelerates Energy when Charizard evolves and
                    Burning Darkness scales as the opponent takes prize cards. This makes Charizard especially
                    good with comeback potential.
                </li>

                <li>
                    <strong>Pidgeot ex:</strong> Pidgeot is one of the most
                    important cards in the list. Quick Search lets you find any card from the deck once per
                    turn, giving Charizard reliable access to Rare Candy, Boss’s Orders, Counter Catcher, recovery
                    cards, etc.
                </li>

                <li>
                    <strong>Rare Candy:</strong> Rare Candy is critical because both Charizard and Pidgeot are Stage 2
                    Pokemon. The deck is strongest when it can skip the Stage 1 step and establish its main engine
                    quickly.
                </li>

                <li>
                    <strong>Counter Catcher:</strong> Because Charizard often plays from behind, Counter Catcher is
                    a powerful gust option. It lets the deck target key Pokemon without using its supporter for the turn.
                </li>
            </ul>
