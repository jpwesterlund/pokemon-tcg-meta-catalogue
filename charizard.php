            <h3>Archetype Overview</h3>

            <p>
                <strong>Charizard ex</strong> is one of the most popular and powerful decks in the format. As a
                Darkness-type attacker, it hits Gardevoir ex for weakness, which is a major advantage
                in the meta game. Charizard’s main appeal is how durable it is and how hard it hits. With 330 HP, it is
                difficult to one-hit KO, and its attack damage increases with each prize card your opponent has taken.
            </p>

            <p>
                Charizard’s Infernal Reign ability allows it to accelerate Energy onto itself when it evolves,
                effectively powering up its own attack without requiring separate Energy attachment. While the one-hit-KO
                decks like Raging Bolt ex and Gholdengo ex make Charizard slightly
                less dominant, it remains a strong choice. It sees additional play when paired with Dragapult ex.
            </p>

            <p>
                <strong>Variants:</strong> The classic Charizard build runs a Pidgeot ex line as its
                engine. Pidgeot’s Quick Search ability lets you search your deck for any card once per turn,
                making Charizard incredibly consistent. This remains the most straightforward and recommended way to
                play Charizard.

            <p>
                <strong>Charizard + Dragapult</strong> is also a popular archetype. That build
                uses Dragapult ex as an early game attacker to spread damage and
                Charizard ex as a late game closer. Both Pokemon can function as main attackers, making
                the deck flexible.
            </p>
        </section>

