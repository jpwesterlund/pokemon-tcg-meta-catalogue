            <h3>Archetype Overview</h3>

            <p>
                <strong>Gardevoir ex</strong> is one of the most successful Pokemon TCG archetypes of all time,
                having just passed $1 million in total prizing won at major tournaments.
                Gardevoir is the queen of comebacks and one of the strongest spread damage decks in the format, next to Pult. 
                Its Psychic Embrace ability allows you to accelerate Psychic Energy from your discard pile onto
                your Psychic Pokemon, at the cost of placing two damage counters for each Energy attached.
            </p>

            <p>
                That downside becomes a strength because the attackers used in Gardevoir deal more damage when they have
                damage counters on them. Drifloon does 30 damage for each damage counter on it.
                Scream Tail does 20 damage per counter and targets Benched Pokemon.
                Because Gardevoir accelerates both Energy and damage, it can take sudden KOs that are hard
                for opponents to predict.
            </p>

            <p>
                Munkidori makes the deck even more powerful by moving damage counters from your own
                board onto your opponent’s board. This gives Gardevoir another way to convert the cost of
                Psychic Embrace, essentially healing off your own attackers and setting up spread damage anywhere on
                your opponent's board.
            </p>

            <p>
                <strong>Variants:</strong> The most common version of Gardevoir includes Drifloon as
                a major single-prize attacker. However, the <strong>Bradner</strong> variant, named after Isaiah
                Bradner’s NAIC winning list, focuses more heavily on Munkidori and spread damage. That
                version cuts Drifloon entirely and includes four copies of Munkidori instead. 
                It also includes a one-of copy of Boss’s Orders for gusting, 
                a tech that many Gardevoir lists had previously dropped.
            </p>
        </section>

