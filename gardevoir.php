        <section>
            <h3>Key Cards</h3>

            <ul>
                <li>
                    <strong>ACE Spec:</strong> The obvious ACE Spec choice is Secret Box. It lets the
                    deck discard Psychic Energy for Psychic Embrace while also searching for resources.
                    Unfair Stamp is also defensible because Gardevoir almost always plays from behind,
                    but Secret Box is objectively the most successful choice.
                </li>

                <li>
                    <strong>Scream Tail:</strong> Scream Tail is one of Gardevoir’s most important attackers. It scales
                    with the number of damage counters on it and can target any of the opponent’s Pokemon, including
                    Pokemon on the bench.
                </li>

                <li>
                    <strong>Munkidori:</strong> Munkidori is one of the deck’s strongest support Pokemon. Since
                    Gardevoir damages its own board while accelerating Energy, Munkidori turns that self-damage into
                    spread damage on the opponent's side of the board.
                </li>

                <li>
                    <strong>Drifloon:</strong> Drifloon gives many Gardevoir builds a way to one-hit KO big HP Pokemon. 
                    Its inclusion is build dependent, but with a Bravery Charm attached to increase its HP (and thus, the amount of 
                    damage counters it can take from Psychic Embrace) it can one-hit KO just about anything in the format.
                </li>
            </ul>
