        <section>
            <h3>Key Cards</h3>

            <ul>
                <li>
                    <strong>ACE Spec:</strong> The strongest ACE Spec choice for Joltik Box is
                    Prime Catcher. The deck is very aggressive and often relies on gusting up low HP
                    Pokemon for Iron Hands ex to knock out with Amp You Very Much.
                    Sparkling Crystal is a possible alternative because
                    Pikachu ex's Topaz Bolt attack requires three Energy, but Prime Catcher
                    is the more successful choice.
                </li>

                <li>
                    <strong>Joltik:</strong> Joltik is the deck’s early game Energy acceleration. Jolting Charge 
                    can power up several attackers at once, giving the deck immediate aggressive lines.
                </li>

                <li>
                    <strong>Iron Hands ex:</strong> Iron Hands is one of the deck’s most important attackers because
                    Amp You Very Much takes an extra prize card when it scores a knockout. This lets Joltik Box
                    punish smaller Pokemon and essentially cheat extra early game prize cards.
                </li>

                <li>
                    <strong>Miraidon ex:</strong> Miraidon’s Tandem Unit ability lets the deck search for any
                    two Lightning-type Basic Pokemon. This makes it easy to find both Joltik and
                    Iron Hands ex on turn one (or Pikachu).
                </li>

                <li>
                    <strong>Mew ex / Fezandipiti ex:</strong> Joltik Box can struggle with draw power, so setting up
                    support Pokemon like Mew or Fezandipiti is often very important to avoid late game dead draws.
                </li>
            </ul>
