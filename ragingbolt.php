        <section>
            <h3>Key Cards</h3>

            <ul>
                <li>
                    <strong>ACE Spec:</strong> Because of how aggressive Bolt is, Prime Catcher is the
                    natural ACE Spec choice. It gives the deck a gust effect without using your supporter for turn. Bolt 
                    essentially wants to use Professor Sada’s Vitality every turn to replenish Energy
                    discarded with Bellowing Thunder. Meaning, many times using Boss's
                    Orders to gust in a turn isn't possible. 
                    Prime Catcher is also easy to find with Noctowl's Jewel Seeker.
                </li>

                <li>
                    <strong>Professor Sada’s Vitality:</strong> This is the most important card in the deck. It
                    accelerates Energy directly to Bolt while also drawing cards. 
                </li>

                <li>
                    <strong>Teal Mask Ogerpon:</strong> Ogerpon gives the deck additional Energy acceleration and
                    draw support through Teal Dance. As a Tera Pokemon, it also enables Noctowl.
                </li>

                <li>
                    <strong>Noctowl:</strong> Noctowl makes Bolt incredibly consistent. 
                    Searching for any two Trainer cards lets the deck find Sada every turn, Prime Catcher when needed,
                    a stadium bump, recovery, etc.
                </li>
            </ul>
        </section>

