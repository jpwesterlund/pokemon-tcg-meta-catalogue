        <section>
            <h3>Key Cards</h3>

            <ul>
                <li>
                    <strong>ACE Spec:</strong> Because Marnie’s Grimmsnarl comes with a stadium
                    that can search out any Marnie’s Pokemon from the deck, Secret Box is the most natural
                    choice. Grimmsnarl also benefits from late game hand disruption, so
                    Unfair Stamp could be a consideration. However, a heavy count of Iono
                    is probably preferable.
                </li>

                <li>
                    <strong>Froslass:</strong> Froslass is Grimmsnarl’s best partner. Its Freezing Shroud
                    ability adds 10 damage to all Pokemon in play with an ability during Pokemon checkup, which stacks with
                    multiple Froslass in play. Combined with
                    Munkidori and Grimmsnarl’s own spread damage from Shadow Bullet, Froslass
                    helps create multi-prize turns.
                </li>

                <li>
                    <strong>Munkidori:</strong> Munkidori lets the deck move damage counters from your own board onto
                    the opponent’s Pokemon. Since Froslass places damage across both boards, Munkidori heals off your own Pokemon
                    and builds up spread damage on your opponent's.
                </li>

                <li>
                    <strong>Arven:</strong> Arven is one of the deck’s most important supporters because it can search out
                    Secret Box. It can also find Technical Machine: Evolution to set up Froslass as early as turn 1, plus
                    Technical Machine: Devolution once enough damage has built up on the opponent's side of the field. 
                </li>
            </ul>
        </section>


