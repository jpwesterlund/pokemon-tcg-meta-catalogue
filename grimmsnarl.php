            <p>
                <strong>Marnie’s Grimmsnarl</strong> is one of the newest competitive archetypes in the format. 
                It was introduced during the <strong>Destined Rivals</strong> format. Grimmsnarl is a spread attacker,
                uniquely positioned in the meta because it hits Gardevoir for weakness. Its
                Punk Up Ability also allows it to accelerate Energy for its own attack when it evolves.
                Its attack, Shadow Bullet, deals 180 damage to the active Pokemon and 30 damage to one of
                the opponent's bench.
            </p>

            <p>
                The general strategy is to use Grimmsnarl in conjunction with Froslass, which adds
                chip damage between turns to all Pokemon in play with abilities. By combining that with
                Munkidori's ability to move that spread damage, Grimmsnarl is capable of setting
                up large multi-prize turns.
            </p>
