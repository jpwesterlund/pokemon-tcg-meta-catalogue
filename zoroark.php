            <h3>Archetype Overview</h3>

            <p>
                <strong>N’s Zoroark ex</strong> is a Trainer’s Pokemon archetype introduced in the
                <strong>Journey Together</strong> format. It is currently positioned as a counter to
                Gardevoir ex because it hits for weakness. Its power became somewhat limited by
                the introduction of Shaymin but Zoroark cycles in and out of competitive viability depending
                on the meta.
            </p>

            <p>
                Zoroark’s attack, Night Joker, copies any attack from any bench N's Pokemon. These attacks
                primarily come from N’s Darmanitan and N’s Reshiram. Darmanitan lets
                you hit both the active Pokemon and a Benched Pokemon for 90 damage each. Reshiram's first attack has a
                20 damage modifier for every damage counter on Zoroark itself or a clean 170 damage for its second.
            </p>

            <p>
                However, Zoroark’s most appealing attribute is the Trade ability. Once per turn, you may discard
                one card to draw two. Because this draw engine is so strong, especially for decks that benefit from
                placing specific cards in the discard pile, N’s Zoroark also sees play as a support
                Pokemon in other archetypes.
            </p>
        </section>

