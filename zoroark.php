        <section>
            <h3>Key Cards</h3>

            <ul>
                <li>
                    <strong>ACE Spec:</strong> Since N’s Pokemon are supported by specific Trainer cards,
                    such as N’s PP Up and N’s Castle,
                    Secret Box is the most natural ACE Spec choice. It gives the deck access to
                    multiple resource types at once and helps assemble the correct attacker setup. However,
                    Prime Catcher is also viable if you want to build a more aggressive version of the
                    deck.
                </li>

                <li>
                    <strong>N’s Zoroark ex:</strong> Zoroark is both the deck’s main attacker and its draw engine.
                    Night Joker gives it multiple attack options by copying attacks from bench N's Pokemon.
                    Trade helps the deck draw cards and place useful resources into the discard
                    pile.
                </li>

                <li>
                    <strong>N’s Darmanitan:</strong> Darmanitan gives Zoroark access to spread pressure by hitting both
                    the active Pokemon and the opponent's bench. It's worth noting that Darmanitan is a stage 1 and its usefulness
                    is dependent on if bench protection is relevant in the current meta game.
                </li>

                <li>
                    <strong>N’s Reshiram:</strong> Zoroark will end up copying one of Reshiram's attacks for most matchups. Its
                    second attack offers a clean 170 damage. However, if the opponent is forced to attack into a Zoroark without KOing
                    it, its second attack can one-hit KO basically anything in the format with enough damage.
                </li>

                <li>
                    <strong>N’s PP Up:</strong> N’s PP Up lets you attach an Energy from the discard pile to one of your
                    N’s Pokemon. This is one of the deck’s most important cards and can help power up
                    Zoroark in a single turn.
                </li>

                <li>
                    <strong>N’s Castle:</strong> N’s Castle gives all of your N’s Pokemon free retreat, which 
                    helps pivot between multiple set-up Zoroarks.
                </li>
            </ul>
        </section>

