        <section>
            <h3>Archetype Overview</h3>

            <p>
                <strong>Dragapult ex</strong> is a spread deck. Its main attack,
                Phantom Dive, does 200 damage to the active and places 6 damage counters
                on the opponent’s bench in any way you like. Note: Shaymin's ability
                only stops damage to the bench. The effect <em>placing damage counters</em>
                is separate in the Pokemon TCG.
            </p>

            <p>
                The deck’s main goal is to build up damage across the opponent’s board so that it can take
                multi-prize turns in the mid to late game. As previously mentioned, 
                Pult also has a built in draw engine through its stage 1 evolution
                Drakloak. Drakloak’s Recon Directive ability lets you look at the top
                two cards of your deck, put one into your hand, and place the other on the bottom of your deck. 
                The benefit of this is that you don't have to forfeit a bench space to dedicated draw Pokemon. 
                You can simply keep a bench full of Drakloaks and only evolve into Pult when ready to attack.
            </p>

            <p>
                <strong>Variants:</strong> Pult accounted for roughly 30% of the NAIC meta. Several major variants
                developed. The most aggressive version is <strong>Pult Noir</strong>.
                This variant uses the Dusknoir line for additional damage counter spread.
                Dusclops and Dusknoir both have the ability Cursed Blast, which
                places 50 and 130 damage counters respectively on an opponent's Pokemon.
                Cursed Blast self-KOs the Dusclops/Dusknoir and gives the opponent a prize card.
            </p>

            <p>
                That self-KO is generally a benefit for Pult. The benefit is that it
                forces the opponent to take a prize card, intentionally putting Pult behind in prizes. 
                This allows the Pult player to use Counter Catcher as a gust option without using your 
                supporter for turn. The Cursed Blast ability can also be used to knockout low HP Pokemon, such as Ralts in
                Gardevoir and Dreepy in the mirror match.
            </p>

            <p>
                Another major variant is Tord Reklev’s <strong>“Slow” Pult</strong>, which ended up being one
                of the best performing Dragapult builds at NAIC 2025. This version focuses on repeatedly 
                item locking your opponent with Budew to stall your opponent's development of their board 
                while building up your own.
            </p>

            <p>
                The final major variant is <strong>Pult Zard</strong>. Dragapult acts as the 
                early game attacker and spreads damage on the opponent’s board before essentially "cleaning up" 
                with Charizard as the late game closer. Both Slow Pult and Pult Zard prefer to play from behind, 
                while Pult Noir manipulates the prize trade with ultra aggressive spread damage lines.
            </p>
        </section>

