        <section>
            <h3>Key Cards</h3>

            <ul>
                <li>
                    <strong>ACE Spec:</strong> Pult has several viable ACE Spec options.
                    Neo Upper Energy is the most popular choice because it allows Pult
                    to use Phantom Dive with a single energy attachment. Since Pult is a Tera Pokemon,
                    Sparkling Crystal serves a similar role in builds with tool search (via Arven). 
                    Unfair Stamp is also a strong alternative because Pult builds generally play from behind and can punish opponents for taking greedy KOs.
                </li>

                <li>
                    <strong>Drakloak:</strong> Drakloak is both the required stage 1 evolution and the deck’s
                    draw engine. Multiple Drakloaks in play make the deck incredibly consistent and
                    help Pult find pieces without relying only on draw supporters.
                </li>

                <li>
                    <strong>Munkidori:</strong> Munkidori adds even more damage counter manipulation 
                    by moving damage off your board and placing it onto the opponent’s board. 
                </li>

                <li>
                    <strong>Budew:</strong> Budew has become a staple in slower Pult builds. Its free attack, Itchy Pollen, item locks the opponent. This can sometimes make your opponent unable to play the 
                    game while Pult develops its board.
                </li>

                <li>
                    <strong>Counter Catcher:</strong> Pult intentionally plays from
                    behind, making Counter Catcher one of the deck’s strongest cards. It allows you to gust
                    Pokemon without spending your supporter for turn.
                </li>
            </ul>
        </section>

